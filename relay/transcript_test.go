func TestParseClaudeLogKeepsOnlyConversation(t *testing.T) {
	log := strings.Join([]string{
		`{"type":"permission-mode","permissionMode":"default"}`,
		`{"type":"user","isMeta":true,"message":{"role":"user","content":"Caveat: generated by local commands"}}`,
		`{"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>\n<command-args></command-args>"}}`,
		`{"type":"user","message":{"role":"user","content":"review auth.go"}}`,
		`{"type":"assistant","message":{"role":"assistant","content":[{"type":"thinking","thinking":"hmm"}]}}`,
		`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Reading it now."}]}}`,
		`{"type":"assistant","message":{"role":"assistant","content":[{"type":"tool_use","name":"Read","input":{}}]}}`,
		`{"type":"user","message":{"role":"user","content":[{"type":"tool_result","content":"package auth"}]}}`,
		`not json`,
		`{"type":"assistant","isSidechain":true,"message":{"role":"assistant","content":[{"type":"text","text":"subagent chatter"}]}}`,
		`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Missing a nil check."}]}}`,
		`{"type":"user","message":{"role":"user","content":[{"type":"text","text":"fix it"}]}}`,
	}, "\n")

	turns, err := parseClaudeLog(strings.NewReader(log))
	require.NoError(t, err)
	require.Equal(t, []turn{
		{roleUser, "review auth.go"},
		{roleAssistant, "Reading it now.\n\nMissing a nil check."},
		{roleUser, "fix it"},
	}, turns)
}

