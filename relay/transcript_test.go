func agyStepLog(steps ...string) string {
	return strings.Join(steps, "\n")
}

const (
	agyUser     = `{"step_index":0,"source":"USER_EXPLICIT","type":"USER_INPUT","status":"DONE","content":"<USER_REQUEST>\nreview auth.go\n</USER_REQUEST>\n<ADDITIONAL_METADATA>\nThe current local time is: now.\n</ADDITIONAL_METADATA>"}`
	agyToolCall = `{"step_index":1,"source":"MODEL","type":"PLANNER_RESPONSE","status":"DONE","content":"Let me read it.","tool_calls":[{"name":"view_file"}]}`
	agyToolOut  = `{"step_index":2,"source":"MODEL","type":"GENERIC","status":"DONE","content":"File Path: auth.go\npackage auth"}`
	agyReply    = `{"step_index":3,"source":"MODEL","type":"PLANNER_RESPONSE","status":"DONE","content":"Missing a nil check.","thinking":"hmm"}`
)

func TestParseAgyLogKeepsOnlyConversation(t *testing.T) {
	turns, err := parseAgyLog(strings.NewReader(agyStepLog(agyUser, agyToolCall, `not json`, agyToolOut, agyReply)))
	require.NoError(t, err)
	require.Equal(t, []turn{
		{roleUser, "review auth.go"},
		{roleAssistant, "Let me read it.\n\nMissing a nil check."},
	}, turns)

	_, err = parseAgyLog(strings.NewReader(agyToolOut))
	require.Error(t, err)
}

func TestParseAgyLogUsesLatestRecordPerStep(t *testing.T) {
	running := `{"step_index":1,"type":"PLANNER_RESPONSE","status":"RUNNING","content":"Miss"}`
	turns, err := parseAgyLog(strings.NewReader(agyStepLog(running, agyUser,
		`{"step_index":1,"type":"PLANNER_RESPONSE","status":"DONE","content":"Missing a nil check."}`)))
	require.NoError(t, err)
	require.Equal(t, []turn{
		{roleUser, "review auth.go"},
		{roleAssistant, "Missing a nil check."},
	}, turns, "steps are ordered by index, and a rewritten step replaces its earlier record")
}

func TestLatestAgyReplyWaitsForTheFinalStep(t *testing.T) {
	got, key, err := latestAgyReply(strings.NewReader(agyStepLog(agyUser, agyToolCall, agyToolOut, agyReply)))
	require.NoError(t, err)
	require.Equal(t, "Missing a nil check.", got)
	require.Equal(t, "3", key)

	_, _, err = latestAgyReply(strings.NewReader(agyStepLog(agyUser, agyToolCall)))
	require.Error(t, err, "narration before a tool call is not the final reply")
	_, _, err = latestAgyReply(strings.NewReader(agyStepLog(agyUser, agyToolCall, agyToolOut)))
	require.Error(t, err, "agy is still working after a tool result")
	_, _, err = latestAgyReply(strings.NewReader(agyStepLog(agyReply, `{"step_index":4,"type":"USER_INPUT","status":"DONE","content":"next"}`)))
	require.Error(t, err, "the previous reply does not answer a newer prompt")
	_, _, err = latestAgyReply(strings.NewReader(`{"step_index":3,"type":"PLANNER_RESPONSE","status":"RUNNING","content":"Miss"}`))
	require.Error(t, err)
}

func TestFindAgyLogFollowsConversationIndex(t *testing.T) {
	root := t.TempDir()
	writeLog(t, filepath.Join(root, "cache", "last_conversations.json"),
		`{"/wt/agy":"conv-1","/wt/escape":"../../etc"}`, time.Now())

	got, err := findAgyLogIn(root, "/wt/agy")
	require.NoError(t, err)
	require.Equal(t, filepath.Join(root, "brain", "conv-1", ".system_generated", "logs", "transcript.jsonl"), got)

	got, err = findAgyLogIn(root, "/wt/escape")
	require.NoError(t, err)
	require.Equal(t, filepath.Join(root, "brain", "etc", ".system_generated", "logs", "transcript.jsonl"), got,
		"a conversation id never leaves the brain directory")

	_, err = findAgyLogIn(root, "/wt/missing")
	require.Error(t, err)
	_, err = findAgyLogIn(t.TempDir(), "/wt/agy")
	require.Error(t, err, "no index yet")

	broken := t.TempDir()
	writeLog(t, filepath.Join(broken, "cache", "last_conversations.json"), `{`, time.Now())
	_, err = findAgyLogIn(broken, "/wt/agy")
	require.Error(t, err)
}

func TestAgyTranscriptAndLatestReplyFromHome(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	root := filepath.Join(home, ".gemini", "antigravity-cli")
	writeLog(t, filepath.Join(root, "cache", "last_conversations.json"), `{"/wt/agy":"c1"}`, time.Now())
	writeLog(t, filepath.Join(root, "brain", "c1", ".system_generated", "logs", "transcript.jsonl"),
		agyStepLog(agyUser, agyReply), time.Now())

	transcript, err := AgentAntigravity.Transcript("/wt/agy")
	require.NoError(t, err)
	require.Contains(t, transcript, "# Gemini session transcript")
	require.Contains(t, transcript, "\n## User\n\nreview auth.go\n\n## Gemini\n\nMissing a nil check.\n")

	// agy keeps a spinner and "esc to cancel" on screen after it answers; the
	// finished reply in the log is what counts.
	reply, id, err := AgentAntigravity.LatestReply("/wt/agy", "  Missing a nil check.\n⣯  Loading...\nesc to cancel        Gemini 3.8 Flash · high")
	require.NoError(t, err)
	require.Equal(t, "Missing a nil check.", reply)
	require.NotEqual(t, [32]byte{}, id)
}

func TestLatestExchange(t *testing.T) {
	root := t.TempDir()
	t.Setenv("CODEX_HOME", root)
	msg := func(role, kind, text string) string {
		return `{"type":"response_item","payload":{"type":"message","role":"` + role + `","content":[{"type":"` + kind + `","text":"` + text + `"}]}}`
	}
	writeLog(t, filepath.Join(root, "sessions", "rollout-x.jsonl"), strings.Join([]string{
		`{"type":"session_meta","payload":{"cwd":"/wt/codex"}}`,
		msg("user", "input_text", "old question"),
		msg("assistant", "output_text", "old answer"),
		msg("user", "input_text", "new question"),
		msg("assistant", "output_text", "new answer"),
		msg("user", "input_text", "unanswered follow-up"),
	}, "\n"), time.Now())

	got, err := AgentCodex.LatestExchange("/wt/codex")
	require.NoError(t, err)
	require.Equal(t, Exchange{User: "new question", Assistant: "new answer"}, got,
		"the latest reply and the message it answers, not a newer unanswered one")

	writeLog(t, filepath.Join(root, "sessions", "rollout-y.jsonl"), strings.Join([]string{
		`{"type":"session_meta","payload":{"cwd":"/wt/fresh"}}`,
		msg("user", "input_text", "hello"),
	}, "\n"), time.Now())
	_, err = AgentCodex.LatestExchange("/wt/fresh")
	require.Error(t, err)
}
